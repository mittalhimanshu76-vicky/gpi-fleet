  static pw.Widget _buildExpenseTable(
    List<Map<String, dynamic>> expenses,
    DateFormat dateFormat,
    pw.Font? unicodeFont,
  ) {
    final headers = [
      'Date',
      'Truck Number',
      'Driver',
      'Expense',
      'Paid By',
      'Payment Mode',
      'Amount',
    ];

    final data = expenses.map((expense) {
      return [
        _formatDate(expense['date']?.toString() ?? '', dateFormat),
        expense['truck_no']?.toString() ?? '',
        expense['driver_name']?.toString() ?? '',
        expense['expense_name']?.toString() ?? '',
        expense['paid_by']?.toString() ?? '',
        expense['payment_mode']?.toString() ?? '',
        _formatCurrency(_parseAmount(expense['amount'])),
      ];
    }).toList();

    final headerStyle = pw.TextStyle(
      font: unicodeFont,
      fontSize: 8,
      fontWeight: pw.FontWeight.bold,
      color: PdfColors.white,
    );
    final baseTextStyle = pw.TextStyle(
      font: unicodeFont,
      fontSize: 8,
      color: PdfColors.grey800,
    );
    final amountStyle = pw.TextStyle(
      font: unicodeFont,
      fontSize: 8,
      fontWeight: pw.FontWeight.bold,
      color: PdfColors.grey800,
    );

    return pw.Container(
      decoration: pw.BoxDecoration(
        border: pw.Border.all(width: 0.6, color: PdfColor.fromInt(0xFFD6D6D6)),
      ),
      child: pw.Table(
        border: pw.TableBorder(
          horizontalInside: const pw.BorderSide(
            width: 0.5,
            color: PdfColor.fromInt(0xFFD6D6D6),
          ),
          verticalInside: const pw.BorderSide(
            width: 0.5,
            color: PdfColor.fromInt(0xFFD6D6D6),
          ),
          left: const pw.BorderSide(
            width: 0.5,
            color: PdfColor.fromInt(0xFFD6D6D6),
          ),
          top: const pw.BorderSide(
            width: 0.5,
            color: PdfColor.fromInt(0xFFD6D6D6),
          ),
          right: const pw.BorderSide(
            width: 0.5,
            color: PdfColor.fromInt(0xFFD6D6D6),
          ),
          bottom: const pw.BorderSide(
            width: 0.5,
            color: PdfColor.fromInt(0xFFD6D6D6),
          ),
        ),
        columnWidths: {
          0: const pw.FlexColumnWidth(1.0),
          1: const pw.FlexColumnWidth(0.85),
          2: const pw.FlexColumnWidth(1.0),
          3: const pw.FlexColumnWidth(1.0),
          4: const pw.FlexColumnWidth(0.9),
          5: const pw.FlexColumnWidth(0.9),
          6: const pw.FlexColumnWidth(0.9),
        },
        children: [
          pw.TableRow(
            decoration: const pw.BoxDecoration(
              color: PdfColor.fromInt(0xFF2E7D32),
            ),
            children: headers.map((header) {
              return pw.Container(
                padding: const pw.EdgeInsets.all(8),
                child: pw.Center(
                  child: pw.Text(
                    header,
                    style: headerStyle,
                    softWrap: false,
                    textAlign: pw.TextAlign.center,
                  ),
                ),
              );
            }).toList(),
          ),
          ...data.asMap().entries.map((entry) {
            final rowIndex = entry.key;
            final rowData = entry.value;
            return pw.TableRow(
              decoration: rowIndex.isEven
                  ? const pw.BoxDecoration(color: PdfColors.white)
                  : const pw.BoxDecoration(color: PdfColor.fromInt(0xFFF8F8F8)),
              children: rowData.asMap().entries.map((cellEntry) {
                final isAmount = cellEntry.key == rowData.length - 1;
                final value = cellEntry.value.toString();
                return pw.Container(
                  padding: const pw.EdgeInsets.all(8),
                  child: pw.Text(
                    value,
                    style: isAmount ? amountStyle : baseTextStyle,
                    softWrap: false,
                    textAlign: isAmount
                        ? pw.TextAlign.right
                        : pw.TextAlign.left,
                  ),
                );
              }).toList(),
            );
          }),
        ],
      ),
    );
  }

  static String _formatDate(String input, DateFormat formatter) {
    final parsed = DateTime.tryParse(input);
    if (parsed != null) return formatter.format(parsed);

    final parts = input.split('/');
    if (parts.length == 3) {
      final day = int.tryParse(parts[0]);
      final month = int.tryParse(parts[1]);
      final year = int.tryParse(parts[2]);
      if (day != null && month != null && year != null) {
        return formatter.format(DateTime(year, month, day));
      }
    }

    return input;
  }

  static String _formatCurrency(double amount) {
    final formatter = NumberFormat('#,##0.00', 'en_US');
    return '₹ ${formatter.format(amount)}';
  }

  static Future<pw.MemoryImage?> _loadLogoImage() async {
    try {
      final bytes = await rootBundle.load('assets/image/gpi_logo.png');
      return pw.MemoryImage(bytes.buffer.asUint8List());
    } catch (_) {
      return null;
    }
  }

  static Future<pw.Font?> _loadUnicodeFont() async {
    final candidates = <String>[
      r'C:\Windows\Fonts\arial.ttf',
      r'C:\Windows\Fonts\arialuni.ttf',
      r'C:\Windows\Fonts\seguiemj.ttf',
    ];

    for (final path in candidates) {
      final file = File(path);
      if (!await file.exists()) continue;

      try {
        final bytes = await file.readAsBytes();
        return pw.Font.ttf(bytes.buffer.asByteData());
      } catch (_) {
        continue;
      }
    }

    return null;
  }

  static double _parseAmount(dynamic value) {
    if (value is num) return value.toDouble();
    if (value is String) return double.tryParse(value) ?? 0.0;
    return 0.0;
  }
}
