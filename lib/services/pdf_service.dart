  static Future<void> generateExpenseReport({
    required List<Map<String, dynamic>> expenses,
    required String truckFilter,
    DateTime? fromDate,
    DateTime? toDate,
  }) async {
    final pdf = pw.Document();
    final dateFormat = DateFormat('yyyy-MM-dd');
    final dateTimeFormat = DateFormat('yyyy-MM-dd HH:mm');
    final unicodeFont = await _loadUnicodeFont();
    final totalAmount = expenses.fold<double>(
      0,
      (sum, expense) => sum + _parseAmount(expense['amount']),
    );
    final generatedOn = dateTimeFormat.format(DateTime.now());
    final logoImage = await _loadLogoImage();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(18),
        build: (pw.Context context) {
          return [
            _buildHeader(logoImage, unicodeFont),
            pw.SizedBox(height: 12),

            pw.SizedBox(height: 14),
            _buildReportDetailsSection(
              truckFilter: truckFilter,
              fromDate: fromDate,
              toDate: toDate,
              generatedOn: generatedOn,
              dateFormat: dateFormat,
              unicodeFont: unicodeFont,
            ),
            pw.SizedBox(height: 12),
            _buildSummarySection(
              totalEntries: expenses.length,
              totalAmount: totalAmount,
              unicodeFont: unicodeFont,
            ),
            pw.SizedBox(height: 12),
            expenses.isEmpty
                ? pw.Center(
                    child: pw.Text(
                      'No expense records found.',
                      style: pw.TextStyle(font: unicodeFont, fontSize: 12),
                    ),
                  )
                : _buildExpenseTable(expenses, dateFormat, unicodeFont),
            pw.SizedBox(height: 12),
            _buildGrandTotalRow(
              totalAmount: totalAmount,
              unicodeFont: unicodeFont,
            ),
          ];
        },
        footer: (pw.Context context) {
          return pw.Container(
            margin: const pw.EdgeInsets.only(top: 8),
            decoration: const pw.BoxDecoration(
              border: pw.Border(
                top: pw.BorderSide(
                  color: PdfColor.fromInt(0xFFD6D6D6),
                  width: 0.6,
                ),
              ),
            ),
            padding: const pw.EdgeInsets.only(top: 6),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      'Generated by',
                      style: pw.TextStyle(
                        font: unicodeFont,
                        fontSize: 8,
                        color: PdfColors.grey700,
                      ),
                    ),
                    pw.Text(
                      'Gautam Parkash India Private Limited',
                      style: pw.TextStyle(
                        font: unicodeFont,
                        fontSize: 8,
                        color: PdfColors.grey700,
                      ),
                    ),
                  ],
                ),
                pw.Text(
                  generatedOn,
                  style: pw.TextStyle(
                    font: unicodeFont,
                    fontSize: 8,
                    color: PdfColors.grey700,
                  ),
                ),
                pw.Text(
                  'Page ${context.pageNumber} of ${context.pagesCount}',
                  style: pw.TextStyle(
                    font: unicodeFont,
                    fontSize: 8,
                    color: PdfColors.grey700,
                  ),
                ),
              ],
            ),
          );
        },
      ),
    );

    await Printing.layoutPdf(onLayout: (format) async => pdf.save());
  }

