      font: unicodeFont,
      fontSize: 11,
      color: PdfColors.grey700,
    );

    final companyStyle = pw.TextStyle(
      font: unicodeFont,
      fontSize: 10,
      fontWeight: pw.FontWeight.bold,
      color: PdfColors.black,
    );

    final infoStyle = pw.TextStyle(
      font: unicodeFont,
      fontSize: 9,
      color: PdfColors.grey700,
    );

    return pw.Container(
      padding: const pw.EdgeInsets.only(bottom: 12),
